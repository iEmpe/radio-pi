"""Display text normalization for UI."""

from __future__ import annotations

_PL_TRANSLATION = str.maketrans(
    {
        "ą": "a",
        "ć": "c",
        "ę": "e",
        "ł": "l",
        "ń": "n",
        "ó": "o",
        "ś": "s",
        "ź": "z",
        "ż": "z",
        "Ą": "A",
        "Ć": "C",
        "Ę": "E",
        "Ł": "L",
        "Ń": "N",
        "Ó": "O",
        "Ś": "S",
        "Ź": "Z",
        "Ż": "Z",
    }
)


def strip_polish_diacritics(text: str) -> str:
    """Replace Polish diacritics with ASCII equivalents for display."""
    if not text:
        return ""
    return text.translate(_PL_TRANSLATION)
